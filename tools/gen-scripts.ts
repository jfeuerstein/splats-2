// Regenerate src/world/scripts.ts: one input script per run, produced by the policy bot at
// default tuning. Run after changing sim defaults or courses: npm run scripts
import { writeFileSync } from "node:fs";
import { defaults } from "../src/tuning";
import { courseWorld, district } from "../src/world/district";
import { runBot } from "../src/sim/bot";

const T = defaults(), d = district();
let out = "// GENERATED by tools/gen-scripts.ts (npm run scripts). Do not edit.\n// One scripted playthrough per run: run-length triples [ticks, hold 0/1, lean*100], valid for DEFAULT tuning.\n\nexport const SCRIPTS: Record<string, number[]> = {\n";
d.courses.forEach((c, i) => {
  const r = runBot(courseWorld(d, i), T);
  if (!r.finished) throw new Error("bot failed " + c.id);
  console.log(c.id, r.seconds.toFixed(1) + "s", "avg", r.avgSpeed.toFixed(1), "landings", r.landings);
  out += `  "${c.id}": [${r.script.join(",")}],\n`;
});
out += "};\n";
writeFileSync(new URL("../src/world/scripts.ts", import.meta.url), out);
